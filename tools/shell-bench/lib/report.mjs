/**
 * Rendering: the same run, as a terminal table or as markdown.
 *
 * Both show the median and the spread rather than a single number. A speedup
 * next to a 20% relative standard deviation is a shrug, and the reader should
 * be able to see that without being told.
 */

import { geomean } from "./stats.mjs";

const LAYER_TITLES = {
  shell: "Layer 1 — the interpreters alone",
  provider: "Layer 2 — through `Computer` (adds the workspace sync)",
};

const LAYER_BLURBS = {
  shell:
    "A fresh interpreter, the fixture files handed to it, the script run. " +
    "No storage, no snapshot, no write-back.",
  provider:
    "`ws.exec(...)` on a real `Workspace` over `MemoryStorage`: everything above, " +
    "plus pushing the workspace in before the command and pulling changes back after.",
};

/**
 * The case list on its own: what each test actually runs, before any timing.
 *
 * Generated from the same definitions the run uses, so the catalogue cannot
 * drift from the suite. `--list` prints it; the report embeds it, because a
 * table of numbers whose rows are opaque ids is not readable on its own.
 */
export function renderCases(cases) {
  const out = [];
  const line = (value = "") => out.push(value);

  line("| case | group | input | heavy | what it runs | note |");
  line("| --- | --- | --- | --- | --- | --- |");
  for (const entry of cases) {
    line(
      `| \`${entry.id}\` | ${entry.group} | ${entry.bytes ? bytes(entry.bytes) : "—"} | ` +
        `${entry.heavy ? "yes" : "—"} | \`${escapePipes(entry.script)}\` | ${entry.note ?? ""} |`,
    );
  }
  return out.join("\n");
}

/** A `|` inside a cell ends the cell unless it is escaped, and scripts are pipes. */
function escapePipes(value) {
  return value.replaceAll("|", "\\|");
}

export function renderConsole(run) {
  const out = [];
  const line = (value = "") => out.push(value);

  line();
  line(bold("cloudfarm shell benchmark — rbash (wasm) vs just-bash (TypeScript)"));
  line(dim(metaLine(run.meta)));

  for (const [layer, cases] of Object.entries(run.layers)) {
    line();
    line(bold(stripMarkdown(LAYER_TITLES[layer])));
    for (const [group, entries] of byGroup(cases)) {
      line();
      line(`  ${bold(group)}`);
      const rows = entries.map((entry) => [
        entry.id,
        entry.bytes ? bytes(entry.bytes) : "—",
        cell(entry.results["just-bash"], run.meta.iterations),
        cell(entry.results.rbash, run.meta.iterations),
        speedupText(entry),
      ]);
      for (const row of table(["case", "input", "just-bash", "rbash", "rbash is"], rows)) {
        line(`    ${row}`);
      }
    }
    line();
    line(`  ${bold("summary")}  ${summaryLine(cases)}`);
  }

  if (run.cold) {
    line();
    line(bold("Cold start (fresh process, median of " + run.cold.runs + ")"));
    const rows = Object.entries(run.cold.phases).map(([id, phase]) => [
      id,
      ms(phase.load),
      phase.ready ? ms(phase.ready) : "—",
      ms(phase.construct),
      ms(phase.first),
      ms(phase.load + phase.ready + phase.construct + phase.first),
    ]);
    for (const row of table(
      ["shell", "import", "wasm init", "construct", "first cmd", "total"],
      rows,
    )) {
      line(`  ${row}`);
    }
  }

  const losses = regressions(run);
  if (losses.length > 0) {
    line();
    line(bold("Where rbash is slower"));
    for (const entry of losses) {
      line(`  ${entry.layer}  ${entry.id}  ${(1 / entry.speedup).toFixed(1)}× slower`);
    }
  }

  const { justOnly, rbashOnly, shared } = run.coverage;
  line();
  line(bold("Command coverage"));
  line(`  shared: ${shared.length}`);
  line(`  just-bash only (${justOnly.length}): ${justOnly.join(" ") || "—"}`);
  line(`  rbash only (${rbashOnly.length}): ${rbashOnly.join(" ") || "—"}`);

  const problems = allCases(run).filter((entry) => failures(entry).length > 0);
  if (problems.length > 0) {
    line();
    line(bold("Cases not timed"));
    for (const entry of problems) {
      for (const [shell, reason] of failures(entry)) {
        line(`  ${entry.layer}  ${entry.id}  ${shell}: ${reason}`);
      }
    }
  }

  const divergent = allCases(run).filter((entry) => entry.parity && entry.parity !== "exact");
  if (divergent.length > 0) {
    line();
    line(bold("Same answer, different bytes"));
    for (const entry of divergent) line(`  ${entry.id}  (${entry.parity})`);
  }

  line();
  return out.join("\n");
}

export function renderMarkdown(run) {
  const out = [];
  const line = (value = "") => out.push(value);

  line("# rbash vs just-bash");
  line();
  line(
    "Generated by `pnpm bench` — see `tools/shell-bench/README.md`. " +
      "Numbers are from one machine and one run; regenerate before quoting them.",
  );
  line();
  line(metaLine(run.meta));
  line();
  line("## Headline");
  line();
  for (const [layer, cases] of Object.entries(run.layers)) {
    line(`- **${stripMarkdown(LAYER_TITLES[layer])}** — ${summaryLine(cases)}`);
  }
  line();
  line("## The cases");
  line();
  line(
    "Every case runs on both shells at both layers. `input` is the fixture it is " +
      "given; `heavy` marks the ones only `--heavy` runs.",
  );
  line();
  line(renderCases(run.cases));
  line();

  for (const [layer, cases] of Object.entries(run.layers)) {
    line(`## ${LAYER_TITLES[layer]}`);
    line();
    line(LAYER_BLURBS[layer]);
    line();
    for (const [group, entries] of byGroup(cases)) {
      line(`### ${group}`);
      line();
      line("| case | input | just-bash | rbash | rbash is | note |");
      line("| --- | --- | --- | --- | --- | --- |");
      for (const entry of entries) {
        line(
          `| \`${entry.id}\` | ${entry.bytes ? bytes(entry.bytes) : "—"} | ` +
            `${cell(entry.results["just-bash"], run.meta.iterations)} | ` +
            `${cell(entry.results.rbash, run.meta.iterations)} | ` +
            `${speedupText(entry)} | ${entry.note ?? ""} |`,
        );
      }
      line();
    }
    line(`**Geometric mean across this layer: ${summaryLine(cases)}**`);
    line();
  }

  if (run.cold) {
    line("## Cold start");
    line();
    line(
      "A fresh `node` process per measurement, median of " +
        `${run.cold.runs}. This is the cost a Worker isolate or a short-lived ` +
        "process pays before the first command runs.",
    );
    line();
    line("| shell | import | wasm init | construct | first command | total |");
    line("| --- | --- | --- | --- | --- | --- |");
    for (const [id, phase] of Object.entries(run.cold.phases)) {
      line(
        `| \`${id}\` | ${ms(phase.load)} | ${phase.ready ? ms(phase.ready) : "—"} | ` +
          `${ms(phase.construct)} | ${ms(phase.first)} | ` +
          `${ms(phase.load + phase.ready + phase.construct + phase.first)} |`,
      );
    }
    line();
  }

  const losses = regressions(run);
  line("## Where rbash is slower");
  line();
  if (losses.length === 0) {
    line("Nowhere: rbash won every timed case in this run.");
  } else {
    line("| layer | case | rbash is | note |");
    line("| --- | --- | --- | --- |");
    for (const entry of losses) {
      line(
        `| ${entry.layer} | \`${entry.id}\` | ${(1 / entry.speedup).toFixed(1)}× slower | ` +
          `${entry.note ?? ""} |`,
      );
    }
  }
  line();

  const { justOnly, rbashOnly, shared } = run.coverage;
  line("## Command coverage");
  line();
  line(`${shared.length} commands in both.`);
  line();
  line(`- **just-bash only (${justOnly.length}):** ${code(justOnly)}`);
  line(`- **rbash only (${rbashOnly.length}):** ${code(rbashOnly)}`);
  line();

  const problems = allCases(run).filter((entry) => failures(entry).length > 0);
  line("## Cases not timed");
  line();
  if (problems.length === 0) {
    line("None: every case ran and produced the expected answer on both shells.");
  } else {
    line("| layer | case | shell | why |");
    line("| --- | --- | --- | --- |");
    for (const entry of problems) {
      for (const [shell, reason] of failures(entry)) {
        line(`| ${entry.layer} | \`${entry.id}\` | ${shell} | ${reason} |`);
      }
    }
  }
  line();

  const divergent = [
    ...new Map(
      allCases(run)
        .filter((entry) => entry.parity && entry.parity !== "exact")
        .map((entry) => [entry.id, entry.parity]),
    ),
  ];
  line("## Same answer, different bytes");
  line();
  if (divergent.length === 0) {
    line("None: both shells produced byte-identical output on every timed case.");
  } else {
    line("Output that matches once whitespace is collapsed, but is not byte-identical:");
    line();
    for (const [id, how] of divergent) line(`- \`${id}\` — ${how}`);
  }
  line();

  line("## Method");
  line();
  line(
    [
      `- Up to ${run.meta.iterations} timed iterations per case after ${run.meta.warmup} warmup runs; the median is reported.`,
      `- A case stops early once it has spent ${run.meta.budget} ms on one shell, with at least three samples; \`n=\` marks those.`,
      "- A fresh interpreter per iteration, because both providers build one per command.",
      "- Fixtures are generated from a fixed seed, so another machine measures the same bytes.",
      "- Every case checks its output against an answer computed in JavaScript from the same",
      "  fixture; a case that does not produce it is reported above rather than timed.",
      "- `±` is the relative standard deviation. Treat a gap smaller than the spread as noise.",
    ].join("\n"),
  );
  line();
  return out.join("\n");
}

function metaLine(meta) {
  return [
    meta.date,
    `node ${meta.node}`,
    `${meta.platform}/${meta.arch}`,
    meta.cpu,
    `just-bash ${meta.justBashVersion}`,
    `rbash ${meta.rbashVersion}`,
    `${meta.iterations}×${meta.warmup}w`,
    meta.heavy ? "heavy cases included" : "heavy cases skipped",
  ].join(" · ");
}

function byGroup(cases) {
  const groups = new Map();
  for (const entry of cases) {
    if (!groups.has(entry.group)) groups.set(entry.group, []);
    groups.get(entry.group).push(entry);
  }
  return groups;
}

function allCases(run) {
  return Object.entries(run.layers).flatMap(([layer, cases]) =>
    cases.map((entry) => Object.assign({ layer }, entry)),
  );
}

/** Every timed case rbash lost, worst first. The part worth acting on. */
function regressions(run) {
  return allCases(run)
    .filter((entry) => entry.speedup !== undefined && entry.speedup < 1)
    .toSorted((a, b) => a.speedup - b.speedup);
}

function failures(entry) {
  const out = [];
  for (const [shell, result] of Object.entries(entry.results)) {
    if (result.status !== "ok") out.push([shell, result.reason ?? result.status]);
  }
  return out;
}

function cell(result, iterations) {
  if (!result || result.status !== "ok") return result?.status === "unsupported" ? "n/a" : "fail";
  // The sample count only when a case hit its time budget and stopped early:
  // a median over three runs deserves to be labelled as one.
  const short = iterations && result.stats.samples < iterations ? ` n=${result.stats.samples}` : "";
  return `${ms(result.stats.median)} ±${Math.round(result.stats.rsd * 100)}%${short}`;
}

function speedupText(entry) {
  if (entry.speedup === undefined) return "—";
  if (entry.speedup >= 1) return `${entry.speedup.toFixed(1)}× faster`;
  return `${(1 / entry.speedup).toFixed(1)}× slower`;
}

function summaryLine(cases) {
  const ratios = cases.map((entry) => entry.speedup).filter((value) => value !== undefined);
  if (ratios.length === 0) return "nothing timed";
  const faster = ratios.filter((value) => value > 1).length;
  return (
    `rbash ${geomean(ratios).toFixed(1)}× faster (geometric mean over ${ratios.length} cases), ` +
    `ahead on ${faster}/${ratios.length}`
  );
}

function ms(value) {
  if (!Number.isFinite(value)) return "—";
  if (value >= 100) return `${value.toFixed(0)} ms`;
  if (value >= 10) return `${value.toFixed(1)} ms`;
  if (value >= 1) return `${value.toFixed(2)} ms`;
  return `${value.toFixed(3)} ms`;
}

function bytes(value) {
  if (value >= 1024 * 1024) return `${(value / 1024 / 1024).toFixed(1)} MB`;
  if (value >= 1024) return `${Math.round(value / 1024)} KB`;
  return `${value} B`;
}

function code(names) {
  return names.length === 0 ? "—" : names.map((name) => `\`${name}\``).join(", ");
}

function table(headers, rows) {
  const widths = headers.map((header, column) =>
    Math.max(visible(header).length, ...rows.map((row) => visible(row[column]).length)),
  );
  const render = (cells) =>
    cells
      .map((value, column) => pad(value, widths[column]))
      .join("  ")
      .trimEnd();
  return [dim(render(headers)), ...rows.map(render)];
}

function pad(value, width) {
  return value + " ".repeat(Math.max(width - visible(value).length, 0));
}

// eslint-disable-next-line no-control-regex -- matching the escapes this file writes
const ANSI = /\u001B\[\d+m/g;
const visible = (value) => String(value).replaceAll(ANSI, "");
const colour = process.stdout.isTTY && !process.env.NO_COLOR;
const bold = (value) => (colour ? `\u001B[1m${value}\u001B[22m` : value);
const dim = (value) => (colour ? `\u001B[2m${value}\u001B[22m` : value);
const stripMarkdown = (value) => value.replaceAll("`", "");
