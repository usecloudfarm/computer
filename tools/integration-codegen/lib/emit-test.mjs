/**
 * Emits `src/index.test.ts`.
 *
 * The generated suite is not a formality. For every action it replays the
 * recorded upstream response from the spec through the real `Computer`, and
 * asserts three separate things: the request that went out (method, path,
 * query, body), the value that came back after mapping, and — once per app —
 * that the credential was applied by the host rather than by a handler. A spec
 * whose paths or mappings are wrong fails here, which is the whole reason the
 * spec is required to carry a sample.
 */

import { evalValue, lit } from "./render.mjs";

const TEST_OPTION = "example";
const TEST_KEY = "test-api-key";
const TEST_USER = "bot@example.com";
const TEST_PASSWORD = "test-api-token";

export function emitTest(spec) {
  const credentials = renderCredentials(spec);
  const first = spec.actions[0];

  const blocks = [
    `  it("exposes every action with the search metadata ranking needs", () => {
    const actions = ${spec.constName}(CREDENTIALS).actions();

    expect(actions.map((action) => action.name)).toEqual([
      ${spec.actions.map((action) => lit(action.name)).join(",\n      ")},
    ]);
    for (const action of actions) {
      expect(action.summary.length).toBeGreaterThan(0);
      expect(action.useCases.length).toBeGreaterThan(0);
      expect(action.example).toContain('run("${spec.id}.');
      // Code mode is synchronous; examples must not teach \`await\`.
      expect(action.example).not.toContain("await");
    }
  });`,
  ];

  if (spec.auth.kind !== "none") {
    blocks.unshift(
      `  it("refuses to construct without a credential, and says how to pass one", () => {
    expect(() => ${spec.constName}(${renderBroken(spec)})).toThrow(/invalid credentials/);
  });

  it("publishes its auth shape without exposing the credential", () => {
    const app = ${spec.constName}(CREDENTIALS);

    expect(app.auth?.kind).toBe(${lit(spec.auth.kind === "basic" ? "basic" : "apiKey")});
    expect(JSON.stringify(app.auth)).not.toContain(${lit(secret(spec))});
  });`,
    );
    blocks.push(credentialTest(spec, first));
  }

  for (const action of spec.actions) blocks.push(actionTest(spec, action));
  blocks.push(failureTest(spec, first));

  return `${banner(spec)}

import { afterEach, describe, expect, it, vi } from "vitest";
import { Computer } from "@cloudfarm/computer";
import { ${spec.constName} } from "./index.js";

/** Replaces global fetch, so no test here ever reaches the network. */
function mockFetch(handler: (request: Request) => Response | Promise<Response>) {
  const spy = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) =>
    handler(input instanceof Request ? input : new Request(input, init)),
  );
  vi.stubGlobal("fetch", spy);
  return spy;
}

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });

/** Records what went out, so a request can be asserted on as well as a result. */
function record(body: unknown, status = 200) {
  const seen: Request[] = [];
  mockFetch((request) => {
    seen.push(request);
    return json(body, status);
  });
  return seen;
}

const CREDENTIALS = ${credentials};

async function workspace() {
  const computer = new Computer({ apps: [${spec.constName}(CREDENTIALS)] });
  return computer.createWorkspace("u1");
}

afterEach(() => vi.unstubAllGlobals());

describe(${lit(spec.name)}, () => {
${blocks.join("\n\n")}
});
`;
}

function banner(spec) {
  return `// Generated by tools/integration-codegen from specs/${spec.id}.mjs.
// Run \`pnpm gen:integrations\` after editing the spec; edits here are overwritten.`;
}

function optionValues(spec) {
  const entries = [];
  for (const [name, option] of Object.entries(spec.options)) {
    if (!option.optional) entries.push([name, option.sample ?? TEST_OPTION]);
  }
  return entries;
}

function renderCredentials(spec) {
  const entries = optionValues(spec).map(([name, value]) => `${name}: ${lit(value)}`);
  if (spec.auth.kind === "apiKey") entries.unshift(`apiKey: ${lit(TEST_KEY)}`);
  if (spec.auth.kind === "basic") {
    entries.unshift(`username: ${lit(TEST_USER)}`, `password: ${lit(TEST_PASSWORD)}`);
  }
  return entries.length === 0 ? "{}" : `{ ${entries.join(", ")} }`;
}

function renderBroken(spec) {
  const field = spec.auth.kind === "basic" ? "password" : "apiKey";
  return `{ ...CREDENTIALS, ${field}: "" }`;
}

function secret(spec) {
  return spec.auth.kind === "basic" ? TEST_PASSWORD : TEST_KEY;
}

function expectedAuthHeader(spec) {
  if (spec.auth.kind === "basic") {
    const encoded = Buffer.from(`${TEST_USER}:${TEST_PASSWORD}`).toString("base64");
    return { header: "authorization", value: `Basic ${encoded}` };
  }
  const prefix = spec.auth.prefix === undefined ? "Bearer" : spec.auth.prefix;
  return {
    header: spec.auth.header ?? "authorization",
    value: prefix ? `${prefix} ${TEST_KEY}` : TEST_KEY,
  };
}

function credentialTest(spec, action) {
  const { header, value } = expectedAuthHeader(spec);
  const headerAsserts = Object.entries(spec.headers)
    .map(
      ([key, headerValue]) =>
        `    expect(seen[0]?.headers.get(${lit(key)})).toBe(${lit(headerValue)});`,
    )
    .join("\n");
  return `  it("signs requests with the credential, applied by the host and not by a handler", async () => {
    const seen = record(${sample(action)});
    const ws = await workspace();

    await ws.run("${spec.id}.${action.name}", ${args(action)});

    expect(seen[0]?.headers.get(${lit(header)})).toBe(${lit(value)});
${headerAsserts}
  });`;
}

/** Everything the generator can know about one request, asserted. */
function actionTest(spec, action) {
  // A raw handler declares no request, so there is nothing to assert about what
  // went out — and binding `seen` to assert nothing is an unused variable.
  const lines = [
    `  it("${action.name} sends the request the spec describes and maps the response", async () => {`,
    action.request
      ? `    const seen = record(${sample(action)});`
      : `    record(${sample(action)});`,
    `    const ws = await workspace();`,
    ``,
    `    const result = await ws.run("${spec.id}.${action.name}", ${args(action)});`,
    ``,
    `    expect(result).toEqual({ status: "ok", value: ${json(action.expect)} });`,
  ];
  const request = action.request;
  if (request) {
    const method = request.graphql ? "POST" : request.method;
    lines.push(`    expect(seen[0]?.method).toBe(${lit(method)});`);
    const url = expectedPath(spec, action);
    if (url) lines.push(`    expect(new URL(seen[0]?.url ?? "").pathname).toBe(${lit(url)});`);
    for (const [key, value] of expectedQuery(action)) {
      lines.push(
        `    expect(new URL(seen[0]?.url ?? "").searchParams.get(${lit(key)})).toBe(${lit(String(value))});`,
      );
    }
    if (request.graphql) {
      const variables = evalValue(request.graphql.variables ?? {}, effective(action));
      if (variables.known) {
        lines.push(
          `    expect(await seen[0]?.clone().json()).toMatchObject({ variables: ${json(variables.value)} });`,
        );
      }
    } else if (request.body) {
      const body = evalValue(request.body, effective(action));
      if (body.known) {
        lines.push(`    expect(await seen[0]?.clone().json()).toEqual(${json(body.value)});`);
      }
    } else if (request.form) {
      const form = evalValue(request.form, effective(action));
      if (form.known) {
        const expected = Object.fromEntries(
          Object.entries(form.value)
            .filter(([, value]) => value !== undefined && value !== null)
            .map(([key, value]) => [key, String(value)]),
        );
        lines.push(
          `    expect(Object.fromEntries(new URLSearchParams(await seen[0]?.clone().text()))).toEqual(${json(expected)});`,
        );
      }
    }
  }
  lines.push(`  });`);
  return lines.join("\n");
}

function failureTest(spec, action) {
  return `  it("turns an upstream 404 into an error result rather than a thrown value", async () => {
    record({ message: "not found" }, 404);
    const ws = await workspace();

    expect(await ws.run("${spec.id}.${action.name}", ${args(action)})).toMatchObject({
      status: "error",
    });
  });`;
}

/** The path the request should land on, computed the way core resolves it. */
function expectedPath(spec, action) {
  const inputs = effective(action);
  const base = spec.baseUrl.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (_match, name) =>
    optionSample(spec, name),
  );
  const path = action.request.graphql
    ? (spec.graphqlPath ?? "graphql")
    : action.request.path.replace(/\{([a-zA-Z][a-zA-Z0-9]*)(\*?)\}/g, (_match, name, raw) => {
        const value = String(inputs[name]);
        return raw ? value : encodeURIComponent(value);
      });
  return new URL(`${base.replace(/\/+$/, "")}/${path.replace(/^\/+/, "")}`).pathname;
}

function optionSample(spec, name) {
  const option = spec.options[name];
  return String(option?.sample ?? TEST_OPTION);
}

function expectedQuery(action) {
  if (!action.request?.query) return [];
  const resolved = evalValue(action.request.query, effective(action));
  if (!resolved.known) return [];
  return Object.entries(resolved.value).filter(
    ([, value]) => value !== undefined && value !== null,
  );
}

/**
 * The arguments the handler really sees: the spec's sample arguments, with the
 * declared defaults filled in. A field the model left out still reaches the
 * upstream request, so the assertion has to expect it.
 */
function effective(action) {
  const defaults = Object.fromEntries(
    Object.entries(action.input)
      .filter(([, field]) => field.default !== undefined)
      .map(([name, field]) => [name, field.default]),
  );
  return { ...defaults, ...action.args };
}

function sample(action) {
  return json(action.sample);
}

function args(action) {
  return json(action.args);
}

/** Spec data as a TypeScript literal. Prettier decides the line breaks. */
function json(value) {
  return JSON.stringify(value);
}
