/** Emits `src/index.ts`: the `createApp` call and its actions. */

import {
  HELPERS,
  lit,
  nameFactory,
  pascal,
  quoteKey,
  renderInputSchema,
  renderMapping,
  renderOutputSchema,
  renderValue,
  template,
} from "./render.mjs";
import { placeholders } from "./spec.mjs";

const HELPER_ORDER = ["at", "str", "num", "bool", "list"];
const BODY_NAMES = ["body", "payload", "response"];

export function emitSource(spec) {
  const state = { helpers: new Set() };
  const actions = spec.actions.map((action) => emitAction(spec, action, state));
  const helpers = HELPER_ORDER.filter((name) => state.helpers.has(name)).map(
    (name) => HELPERS[name],
  );

  const imports = ["createAction", "createApp"];
  if (spec.auth.kind === "apiKey") imports.push("apiKey");
  if (spec.auth.kind === "basic") imports.push("basic");
  if (spec.auth.kind === "none") imports.push("noAuth");
  if (spec.validate) imports.push("UpstreamRejectedError");
  imports.sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()));

  const parts = [
    banner(spec),
    `import { z } from "zod";`,
    `import { ${imports.join(", ")} } from "@cloudfarm/computer";`,
    "",
  ];
  if (!spec.templated) parts.push(`const BASE = ${lit(spec.baseUrl)};`, "");
  parts.push(
    docblock(spec),
    `export const ${spec.constName} = createApp({`,
    `  id: ${lit(spec.id)},`,
    `  name: ${lit(spec.name)},`,
    `  description: ${lit(spec.description)},`,
    `  auth: ${renderAuth(spec)},`,
    `  options: ${renderOptions(spec)},`,
    `  allowedHosts: ${renderHosts(spec)},`,
    `  http: ${renderHttp(spec)},`,
    ``,
    `  actions: {`,
    actions.join("\n\n"),
    `  },`,
    `});`,
    "",
    `/** What \`${spec.constName}(…)\` takes: the auth scheme's input plus the options schema. */`,
    `export type ${pascal(spec.id)}Options = Parameters<typeof ${spec.constName}>[0];`,
  );
  if (helpers.length > 0) {
    parts.push(
      "",
      "// --- response mapping -------------------------------------------------------",
      "",
      helpers.join("\n\n"),
    );
  }
  return parts.join("\n") + "\n";
}

function banner(spec) {
  return `// Generated by tools/integration-codegen from specs/${spec.id}.mjs.
// Run \`pnpm gen:integrations\` after editing the spec; edits here are overwritten.
`;
}

function docblock(spec) {
  const lines = [`${spec.name} as an app plugin.`, "", ...spec.notes];
  const body = lines
    .flatMap((line) => wrap(line, 74))
    .map((line) => (line ? ` * ${line}` : " *"))
    .join("\n");
  return `/**\n${body}\n */`;
}

function wrap(text, width) {
  if (!text) return [""];
  const words = text.split(/\s+/);
  const lines = [];
  let line = "";
  for (const word of words) {
    if (line && line.length + 1 + word.length > width) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

function renderAuth(spec) {
  if (spec.auth.kind === "none") return "noAuth()";
  if (spec.auth.kind === "basic") return "basic()";
  const options = [];
  if (spec.auth.header) options.push(`header: ${lit(spec.auth.header)}`);
  if (spec.auth.prefix !== undefined) options.push(`prefix: ${lit(spec.auth.prefix)}`);
  if (spec.auth.describe) options.push(`describe: ${lit(spec.auth.describe)}`);
  return options.length === 0 ? "apiKey()" : `apiKey({ ${options.join(", ")} })`;
}

function renderOptions(spec) {
  const lines = Object.entries(spec.options).map(([name, option]) => {
    let expr = "z.string()";
    if (option.optional) expr += ".optional()";
    if (option.describe) expr += `.describe(${lit(option.describe)})`;
    return `  ${quoteKey(name)}: ${expr},`;
  });
  lines.push(
    `  baseUrl: z.string().url().optional().describe("Override the API base, for a proxy or a test double."),`,
  );
  return `z.object({\n${lines.join("\n")}\n})`;
}

/** Only the options a host list or base URL actually interpolates get bound. */
function destructure(sources, extra = []) {
  const names = new Set(extra);
  for (const source of sources) for (const name of placeholders(source)) names.add(name);
  return names.size === 0 ? "()" : `({ ${[...names].join(", ")} })`;
}

function interpolate(text) {
  return placeholders(text).length === 0
    ? lit(text)
    : `\`${text.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, "${$1}")}\``;
}

function renderHosts(spec) {
  const hosts = spec.allowedHosts.map(interpolate).join(", ");
  return `${destructure(spec.allowedHosts)} => [${hosts}]`;
}

function renderHttp(spec) {
  const lines = [`baseUrl: baseUrl ?? ${spec.templated ? interpolate(spec.baseUrl) : "BASE"},`];
  const headers = Object.entries(spec.headers);
  if (headers.length > 0) {
    lines.push(
      `headers: {\n${headers.map(([key, value]) => `  ${quoteKey(key)}: ${lit(value)},`).join("\n")}\n},`,
    );
  }
  if (spec.validate) lines.push(renderValidate(spec));
  return `${destructure([spec.baseUrl], ["baseUrl"])} => ({\n${lines.join("\n")}\n})`;
}

function renderValidate(spec) {
  const kind = spec.validate.kind;
  if (kind === "graphqlErrors") {
    return `/**
 * ${spec.name} answers 200 with a top-level \`errors\` array, so the body is
 * the only reliable signal. \`UpstreamRejectedError\` is what carries that to
 * the model as a rejection rather than an anonymous internal fault.
 */
validate: (body) => {
  const errors = (body as { errors?: Array<{ message?: string }> }).errors;
  if (errors && errors.length > 0) {
    throw new UpstreamRejectedError(
      \`${spec.name} rejected the request: \${errors[0]?.message ?? "unknown_error"}\`,
    );
  }
},`;
  }
  const field = spec.validate.field ?? (kind === "okFlag" ? "ok" : "success");
  const errorField = spec.validate.errorField ?? "error";
  const retryable = spec.validate.retryable ?? [];
  const retryExpr =
    retryable.length === 0 ? "" : `, [${retryable.map(lit).join(", ")}].includes(reason)`;
  return `/** ${spec.name} answers 200 with \`{ ${field}: false, ${errorField} }\`. */
validate: (body) => {
  const payload = body as Record<string, unknown>;
  if (payload[${lit(field)}] === false) {
    const reason = String(payload[${lit(errorField)}] ?? "unknown_error");
    throw new UpstreamRejectedError(\`${spec.name} rejected the request: \${reason}\`${retryExpr});
  }
},`;
}

// --- actions ----------------------------------------------------------------

function emitAction(spec, action, state) {
  const where = `spec ${spec.id}.${action.name}`;
  const inputs = new Set(Object.keys(action.input));
  const used = new Set();
  const handler = action.handler
    ? action.handler
    : renderHandler(spec, action, inputs, used, state, where);

  if (!action.handler) {
    for (const name of inputs) {
      if (!used.has(name)) {
        throw new Error(
          `${where}: input "${name}" is declared but never used by the request. ` +
            `Either reference it as "$${name}" or drop it — a field the model can set ` +
            `and the request ignores is a lie in the tool definition.`,
        );
      }
    }
  }

  const lines = [
    `    ${action.name}: createAction({`,
    `      summary: ${lit(action.summary)},`,
    `      useCases: [${action.useCases.map(lit).join(", ")}],`,
  ];
  if (action.keywords.length > 0) {
    lines.push(`      keywords: [${action.keywords.map(lit).join(", ")}],`);
  }
  lines.push(
    `      sideEffects: ${lit(action.sideEffects)},`,
    `      input: ${renderInputSchema(action.input, where)},`,
    `      output: ${renderOutputSchema(action.output, where)},`,
    `      example: ${lit(renderExample(action))},`,
    `      handler: ${handler},`,
    `    }),`,
  );
  return lines.join("\n");
}

/**
 * The example is the input literal only — core wraps it in `run("app.name", …)`
 * so a ref in prompt text cannot drift from the action it documents.
 */
function renderExample(action) {
  if (typeof action.example === "string") return action.example;
  const entries = Object.entries(action.example).map(
    ([key, value]) => `${quoteKey(key)}: ${JSON.stringify(value)}`,
  );
  return entries.length === 0 ? "{}" : `{ ${entries.join(", ")} }`;
}

function renderHandler(spec, action, inputs, used, state, where) {
  const call = renderRequest(spec, action, inputs, used, where);
  const bodyName = BODY_NAMES.find((name) => !inputs.has(name)) ?? "upstream";
  const scope = { consts: [], name: nameFactory() };
  const mapping = renderMapping(action.output, bodyName, "", state, scope, where);

  const params = renderParams(action.input, used);
  // An action with nothing to map — a 204, or a body that says only that it
  // worked — must not bind the response, or the binding is an unused variable.
  const reads = mapping !== "{}";
  const lines = [
    `async (${params}, context) => {`,
    reads ? `  const ${bodyName} = await ${call};` : `  await ${call};`,
  ];
  for (const line of scope.consts) lines.push(`  ${line}`);
  lines.push(`  return ${mapping};`, `}`);
  return lines.join("\n");
}

function renderParams(input, used) {
  const bindings = Object.entries(input)
    .filter(([name]) => used.has(name))
    .map(([name, field]) =>
      field.default === undefined ? name : `${name} = ${JSON.stringify(field.default)}`,
    );
  return bindings.length === 0 ? "_input" : `{ ${bindings.join(", ")} }`;
}

function renderRequest(spec, action, inputs, used, where) {
  const request = action.request;
  if (request.graphql) {
    const variables = request.graphql.variables
      ? renderValue(request.graphql.variables, inputs, used, where)
      : "{}";
    const path = lit(spec.graphqlPath ?? "graphql");
    return `context.http.post(${path}, {
  query: ${template(request.graphql.query.trim())},
  variables: ${variables},
})`;
  }

  const path = renderPath(request.path, inputs, used, where);
  const options = [];
  if (request.query) {
    options.push(`query: ${renderValue(request.query, inputs, used, where)}`);
  }
  if (request.form) {
    options.push(`form: ${renderValue(request.form, inputs, used, where)}`);
  }
  if (request.headers) {
    options.push(`headers: ${renderValue(request.headers, inputs, used, where)}`);
  }
  const optionsExpr = options.length === 0 ? null : `{ ${options.join(", ")} }`;
  const method = request.method.toLowerCase();

  if (method === "get" || method === "delete") {
    return optionsExpr
      ? `context.http.${method}(${path}, ${optionsExpr})`
      : `context.http.${method}(${path})`;
  }
  const body = request.body ? renderValue(request.body, inputs, used, where) : null;
  const args = [path];
  if (body) args.push(body);
  else if (optionsExpr) args.push("undefined");
  if (optionsExpr) args.push(optionsExpr);
  return `context.http.${method}(${args.join(", ")})`;
}

/**
 * `{id}` is percent-encoded; `{repo*}` is not, for the APIs whose path segment
 * is itself a path ("owner/name"). Encoding by default is the safe direction:
 * an argument arriving from a model must not be able to climb the URL.
 */
function renderPath(pathTemplate, inputs, used, where) {
  if (!/\{/.test(pathTemplate)) return lit(pathTemplate);
  const rendered = pathTemplate.replace(/\{([a-zA-Z][a-zA-Z0-9]*)(\*?)\}/g, (_match, name, raw) => {
    if (!inputs.has(name)) throw new Error(`${where}: path uses {${name}}, not an input field.`);
    used.add(name);
    return raw ? `\${${name}}` : `\${encodeURIComponent(String(${name}))}`;
  });
  return `\`${rendered}\``;
}
